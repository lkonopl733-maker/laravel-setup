<?php
// Пункт 1: Створення базового PHP-скрипта
// Інструкція echo використовується для виводу тексту на екран.
echo "Hello, World!\n<br>"; 
// Пункт 2: Змінні та типи даних
// Оголошення змінних різних типів 
$stringVar = "Куку";
$intVar = 25; 
$floatVar = 4.75;
$boolVar = true;

echo "<br>--- Змінні та echo ---<br>";
// Виведення значень змінних за допомогою echo
echo "Рядок: " . $stringVar . "<br>";
echo "Ціле число: " . $intVar . "<br>";
echo "Дійсне число: " . $floatVar . "<br>";
echo "Булеве значення: " . ($boolVar ? 'true' : 'false') . "<br>";

echo "<br>--- Інформація про типи (var_dump) ---<br>";
// Функція var_dump виводить тип та значення змінної
echo "<pre>"; // Тег <pre> зберігає форматування для зручного читання var_dump
var_dump($stringVar); 
var_dump($intVar);    
var_dump($floatVar);  
var_dump($boolVar);   
echo "</pre>";
// Пункт 3: Конкатенація рядків
//  дві змінні з рядковими значеннями
$firstName = "Єлизавета";
$lastName = "Конопля";

// об'єднання рядків виконується за допомогою крапки (.)
$fullName = $firstName . " " . $lastName;

echo "<br>--- об'єднання ---<br>";
echo "Повне ім'я: " . $fullName . "<br>"; // результати
// Пункт 4: Умовні конструкції
// змінна з числовим значенням
$number = 14;

echo "<br>--- Перевірка парності числа ---<br>";
// Оператор % повертає остачу від ділення. Якщо остача від ділення на 2 дорівнює 0, число парне.
if ($number % 2 == 0) {
    echo "Число $number є парним.<br>";
} else {
    echo "Число $number є непарним.<br>";
}
// Пункт 5: Цикли
echo "<br>--- Цикл for (від 1 до 10) ---<br>";
for ($i = 1; $i <= 10; $i++) {
    echo $i . " "; 
}
echo "<br>";

echo "<br>--- Цикл while (від 10 до 1) ---<br>";
$j = 10;
// Цикл працює, поки j більше або дорівнює 1
while ($j >= 1) {
    echo $j . " "; 
    $j--;          
}
echo "<br>";
// Пункт 6: Масиви
echo "<br>--- Асоціативний масив ---<br>";
$student = [
    "firstName" => "Ліза",
    "lastName" => "Конопля",
    "age" => 19,
    "specialty" => "Комп'ютерні науки"
];

// Виведення елементів масиву
echo "Ім'я: " . $student["firstName"] . "<br>";
echo "Прізвище: " . $student["lastName"] . "<br>";
echo "Вік: " . $student["age"] . "<br>";
echo "Спеціальність: " . $student["specialty"] . "<br>";

// Додавання нового елемента до масиву
$student["averageGrade"] = 4.8;

echo "<br>--- Оновлений масив студента ---<br>";
// Перегляд всієї структури оновленого масиву
echo "<pre>";
var_dump($student);
echo "</pre>";
?>